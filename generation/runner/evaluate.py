"""Compile gate and oracle scoring for a generated candidate.

The candidate is never written into the user's checkout. The runner copies the
Go module into a scratch workspace, drops the candidate into the family package
there (the wiring contract from generation/README.md), generates a driver that
binds it through the family's own `TaskFor` and scores it with the shipped
`harness.CheckFinancial`, and runs that. `harness/`, `tasks/`, `cmd/`, and
`go.mod` are copied verbatim and never modified.
"""

import json
import os
import re
import shutil
import subprocess
import tempfile

from .families import FACTORY_NAME, FAMILIES, ROOT

CANDIDATE_FILE = "candidate_llm.go"
BUILD_TIMEOUT = 300
RUN_TIMEOUT = 120

INVARIANTS = (
    "at_most_one",
    "no_lost_effect",
    "no_false_dedup",
    "payload_consistency",
    "reproducible",
    "recovery",
)

_FENCE = re.compile(r"```(?:go|golang)?[ \t]*\n(.*?)```", re.S)
_PACKAGE = re.compile(r"^package\s+\w+", re.M)
_FACTORY = re.compile(
    r"^func\s+([A-Za-z_]\w*)\s*\(\s*\w+\s+harness\.Env\s*\)\s*Service\b", re.M
)

_DRIVER_TMPL = """// Code generated by generation/runner. DO NOT EDIT.
package main

import (
	"encoding/json"
	"fmt"
	"os"

	"t4bench/harness"
	"t4bench/tasks/{family}"
)

func main() {{
	cases := {family}.Cases()
	if os.Getenv("T4EVAL_SUBSET") == "public" {{
		cases = {family}.PublicCases()
	}}
	out := []harness.Result{{}}
	for _, c := range cases {{
		out = append(out, score(c))
	}}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	if err := enc.Encode(out); err != nil {{
		fmt.Fprintln(os.Stderr, "encode:", err)
		os.Exit(1)
	}}
}}

// score runs one case. A panic inside the candidate is contained so that a
// single bad schedule does not discard the verdicts for every other schedule;
// the runner reconciles anything still missing as a crashed record.
func score(c {family}.Case) (res harness.Result) {{
	defer func() {{
		if r := recover(); r != nil {{
			fmt.Fprintf(os.Stderr, "panic on %s: %v\\n", c.Sch.ID, r)
			res = harness.Result{{
				Family: {family}.Family, SemanticTask: "{semantic}",
				Candidate: "{candidate}", CorrectRef: false,
				ScheduleID: c.Sch.ID, Seed: c.Sch.Seed, Hidden: c.Sch.Hidden,
				CompileStatus: "success", RuntimeStatus: "crashed",
				Invariants: map[string]bool{{}}, OK: false,
			}}
		}}
	}}()
	obs := harness.Run(c.Sch, {family}.TaskFor({family}.{factory}))
	verdict := harness.CheckFinancial(obs, c.Exp)
	runtime := "completed"
	if obs.NonConvergent {{
		runtime = "nonconvergent"
	}}
	return harness.NewResult(
		{family}.Family, "{semantic}", "{candidate}", false, c.Sch, runtime, verdict)
}}
"""

_LISTER_TMPL = """// Code generated by generation/runner. DO NOT EDIT.
package main

import (
	"encoding/json"
	"os"

{imports}
)

type sched struct {{
	ID     string `json:"schedule_id"`
	Seed   int64  `json:"seed"`
	Hidden bool   `json:"hidden"`
}}

func main() {{
	out := map[string][]sched{{}}
{bodies}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	if err := enc.Encode(out); err != nil {{
		os.Exit(1)
	}}
}}
"""


def extract_go_source(text: str) -> str:
    """Pull the Go file out of a model response.

    Strips markdown fences and any prose around the file — an output-format
    artifact, not a Go-correctness one. The code itself (package clause,
    imports, bodies) is never rewritten: it is compiled exactly as returned, so
    `compile_status` stays an honest measurement. The full raw response is
    archived alongside the extracted file for audit.
    """
    for block in _FENCE.findall(text):
        if _PACKAGE.search(block):
            return block.strip() + "\n"
    blocks = _FENCE.findall(text)
    if blocks:
        return blocks[0].strip() + "\n"
    match = _PACKAGE.search(text)
    if match:
        return text[match.start() :].strip() + "\n"
    return ""


def detect_factory(source: str) -> str:
    """Return the candidate's factory name, preferring the requested one."""
    names = _FACTORY.findall(source)
    if not names:
        return ""
    return FACTORY_NAME if FACTORY_NAME in names else names[0]


class EvalOutcome:
    def __init__(self, compile_status, results=None, error="", factory=""):
        self.compile_status = compile_status  # "success" | "error"
        self.results = results or []
        self.error = error
        self.factory = factory


class Workspace:
    """A scratch copy of the Go module used to compile and score candidates."""

    _SKIP = {".git", ".venv", "venv", "results", "analysis", "__pycache__", "bin"}

    def __init__(self, scratch_root=None):
        self.root = tempfile.mkdtemp(prefix="t4eval-", dir=scratch_root)
        self.module = os.path.join(self.root, "module")
        self._copy_module()
        self._schedules = None

    def _copy_module(self):
        os.makedirs(self.module, exist_ok=True)
        shutil.copy2(os.path.join(ROOT, "go.mod"), os.path.join(self.module, "go.mod"))
        for sub in ("harness", "tasks"):
            shutil.copytree(
                os.path.join(ROOT, sub),
                os.path.join(self.module, sub),
                ignore=shutil.ignore_patterns(*self._SKIP),
            )

    def _go(self, args, timeout, env_extra=None):
        env = dict(os.environ)
        env.setdefault("CGO_ENABLED", "0")
        if env_extra:
            env.update(env_extra)
        return subprocess.run(
            ["go", *args],
            cwd=self.module,
            capture_output=True,
            text=True,
            timeout=timeout,
            env=env,
        )

    # -- schedule metadata -------------------------------------------------

    def schedules(self) -> dict:
        """family -> [{schedule_id, seed, hidden}], independent of any candidate.

        Needed so a candidate that fails to compile still yields one record per
        schedule, as the record contract requires.
        """
        if self._schedules is not None:
            return self._schedules
        pkg_dir = os.path.join(self.module, "cmd", "t4schedules")
        os.makedirs(pkg_dir, exist_ok=True)
        imports = "\n".join(f'\t"t4bench/tasks/{f}"' for f in FAMILIES)
        bodies = "\n".join(
            f'\tfor _, c := range {f}.Cases() {{\n'
            f'\t\tout["{f}"] = append(out["{f}"], '
            f"sched{{c.Sch.ID, c.Sch.Seed, c.Sch.Hidden}})\n\t}}"
            for f in FAMILIES
        )
        with open(os.path.join(pkg_dir, "main.go"), "w", encoding="utf-8") as fh:
            fh.write(_LISTER_TMPL.format(imports=imports, bodies=bodies))
        build = self._go(
            ["build", "-o", "t4schedules", "./cmd/t4schedules"], BUILD_TIMEOUT
        )
        if build.returncode != 0:
            raise RuntimeError(f"failed to build the schedule lister:\n{build.stderr}")
        run = subprocess.run(
            [os.path.join(self.module, "t4schedules")],
            cwd=self.module,
            capture_output=True,
            text=True,
            timeout=RUN_TIMEOUT,
        )
        if run.returncode != 0:
            raise RuntimeError(f"schedule lister failed:\n{run.stderr}")
        self._schedules = json.loads(run.stdout)
        return self._schedules

    # -- candidate evaluation ---------------------------------------------

    def evaluate(self, family_name, source, candidate_id, subset="all") -> EvalOutcome:
        """Compile `source` inside the family package and score it, or report why not."""
        fam = FAMILIES[family_name]
        cand_path = os.path.join(self.module, "tasks", fam.name, CANDIDATE_FILE)
        driver_dir = os.path.join(self.module, "cmd", "t4eval")
        binary = os.path.join(self.module, "t4eval")

        if not source.strip():
            return EvalOutcome("error", error="model returned no Go source")
        factory = detect_factory(source)
        if not factory:
            return EvalOutcome(
                "error",
                error=(
                    "no factory matching `func Name(env harness.Env) Service` was "
                    "found in the generated file"
                ),
            )

        os.makedirs(driver_dir, exist_ok=True)
        try:
            with open(cand_path, "w", encoding="utf-8") as fh:
                fh.write(source)
            with open(os.path.join(driver_dir, "main.go"), "w", encoding="utf-8") as fh:
                fh.write(
                    _DRIVER_TMPL.format(
                        family=fam.name,
                        semantic=fam.semantic_task_id,
                        candidate=candidate_id,
                        factory=factory,
                    )
                )

            try:
                build = self._go(["build", "-o", "t4eval", "./cmd/t4eval"], BUILD_TIMEOUT)
            except subprocess.TimeoutExpired:
                return EvalOutcome("error", error="go build timed out", factory=factory)
            if build.returncode != 0:
                return EvalOutcome("error", error=build.stderr.strip(), factory=factory)

            try:
                run = subprocess.run(
                    [binary],
                    cwd=self.module,
                    capture_output=True,
                    text=True,
                    timeout=RUN_TIMEOUT,
                    env={**os.environ, "T4EVAL_SUBSET": subset},
                )
            except subprocess.TimeoutExpired:
                return EvalOutcome(
                    "success",
                    results=[],
                    error=f"candidate did not terminate within {RUN_TIMEOUT}s",
                    factory=factory,
                )

            if not run.stdout.strip():
                return EvalOutcome(
                    "success",
                    results=[],
                    error=(run.stderr or "driver produced no output").strip(),
                    factory=factory,
                )
            try:
                results = json.loads(run.stdout)
            except json.JSONDecodeError as exc:
                return EvalOutcome(
                    "success", results=[], error=f"unparseable driver output: {exc}", factory=factory
                )
            for rec in results:
                inv = rec.get("invariants") or {}
                rec["invariants"] = {k: bool(inv.get(k, False)) for k in INVARIANTS}
            return EvalOutcome("success", results=results, error=run.stderr.strip(), factory=factory)
        finally:
            for path in (cand_path, os.path.join(driver_dir, "main.go")):
                if os.path.exists(path):
                    os.remove(path)

    def cleanup(self):
        shutil.rmtree(self.root, ignore_errors=True)


def go_available() -> bool:
    return shutil.which("go") is not None
