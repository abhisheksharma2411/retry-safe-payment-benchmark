#!/usr/bin/env python3
"""Regenerate every measured figure and table from the archived pilot results.

Input : results/pilot_results.json   (produced by `go run ./cmd/t4run`)
Output: analysis/figures/*.png       (figures for the README / artifact)
        analysis/figures/paper_data.tex  (pgfplots coordinates for the paper)
        results/metrics_summary.json  (headline numbers)
        results/metrics.csv           (per-candidate table)

All numbers are measured, deterministic harness output — no synthetic data.
This script is the reproducible bridge from raw results to paper artifacts.
"""
import json
import os
import math
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RESULTS = os.path.join(ROOT, "results", "pilot_results.json")
FIGDIR = os.path.join(HERE, "figures")
os.makedirs(FIGDIR, exist_ok=True)

INVARIANTS = ["at_most_one", "no_lost_effect", "no_false_dedup",
              "payload_consistency", "reproducible", "recovery"]
# Canonical mutant "type" across families (m4 has family-specific names).
MUTANT_TYPES = {
    "correct": "correct",
    "m1_unstable_identity": "m1 unstable-identity",
    "m2_no_payload_check": "m2 no-payload-check",
    "m3_raw_key_only": "m3 raw-key-only",
    "m5_recovery_loops": "m5 recovery-loops",
    "m6_replay_new_reference": "m6 replay-new-reference",
}
def mutant_type(name):
    if name in MUTANT_TYPES:
        return MUTANT_TYPES[name]
    if name.startswith("m4_"):
        return "m4 vacuous-success"
    return name


_DIGIT_WORDS = {
    "0": "zero", "1": "one", "2": "two", "3": "three", "4": "four",
    "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine",
}


def tex_name(s):
    """A LaTeX-safe control-sequence suffix: letters only, digits spelled out.

    Digits cannot be dropped or kept. A TeX control sequence is a run of
    catcode-11 letters, so `\\failcompm1unstableidentity` does not define a macro
    of that name — it defines `\\failcompm` with `1unstableidentity` as delimiter
    text, and the five mutant lines silently collided onto that one macro, each
    overwriting the last. Mapping 1 -> "one" keeps every name a real, distinct
    control sequence (`\\failcompmoneunstableidentity`).
    """
    out = []
    for ch in str(s):
        if ch.isalpha():
            out.append(ch)
        elif ch in _DIGIT_WORDS:
            out.append(_DIGIT_WORDS[ch])
    return "".join(out)


def choose(n, k):
    if k < 0 or k > n:
        return 0
    return math.comb(n, k)


def survival_rk(m, n, k):
    """R_k = C(m,k)/C(n,k): probability of surviving k hidden schedules sampled
    without replacement, given m of n passed. (Review issue T4.)"""
    if k <= 0:
        return 1.0
    den = choose(n, k)
    if den == 0:
        return 0.0
    return choose(m, k) / den


def load():
    with open(RESULTS) as f:
        return json.load(f)


def main():
    rows = load()

    # ---- aggregate by canonical candidate type over the HIDDEN set ----
    hidden_pass = defaultdict(int)
    hidden_total = defaultdict(int)
    all_pass = defaultdict(int)
    all_total = defaultdict(int)
    for r in rows:
        t = mutant_type(r["candidate"])
        all_total[t] += 1
        if r["ok"]:
            all_pass[t] += 1
        if r["hidden"]:
            hidden_total[t] += 1
            if r["ok"]:
                hidden_pass[t] += 1

    order = ["correct", "m1 unstable-identity", "m2 no-payload-check",
             "m3 raw-key-only", "m4 vacuous-success", "m5 recovery-loops",
             "m6 replay-new-reference"]
    order = [t for t in order if t in hidden_total]

    # ---- Figure 1: survival curves R_k (measured) ----
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # Colorblind-safe (Okabe-Ito) palette; distinct markers so it also reads in grayscale.
    palette = ["#000000", "#E69F00", "#56B4E9", "#009E73", "#CC79A7", "#0072B2"]
    markers = ["o", "s", "^", "D", "v", "P"]

    kmax = 8
    tex_lines = [
        "% Auto-generated by analysis/make_figures.py — measured pilot data.",
        "% Do not edit by hand; regenerate with `make reproduce-small`.",
        "%",
        "% Every figure in the paper is drawn from the coordinate blocks below, so a",
        "% plotted number cannot drift from the measured records in results/. Each",
        "% block is a pgfplots coordinate list usable directly as:",
        "%     \\addplot coordinates {\\survivalcorrect};",
        "%",
        "% ---------------------------------------------------------------------------",
        "% Survival curves. Coordinates are (k, R_k): the probability that a candidate",
        "% which passed m of n hidden schedules survives k drawn without replacement.",
        "% ---------------------------------------------------------------------------",
    ]
    plt.figure(figsize=(5.4, 3.4))
    for i, t in enumerate(order):
        n = hidden_total[t]
        m = hidden_pass[t]
        ks = list(range(1, min(kmax, n) + 1))
        ys = [survival_rk(m, n, k) for k in ks]
        plt.plot(ks, ys, marker=markers[i % len(markers)], color=palette[i % len(palette)],
                 label=f"{t} ({m}/{n})", linewidth=1.6, markersize=5)
        coords = " ".join(f"({k},{survival_rk(m,n,k):.4f})" for k in ks)
        tex_lines.append(f"\\def\\survival{tex_name(t)}{{{coords}}}  % {m}/{n} hidden passed")
    plt.xlabel("$k$ (independent hidden fault schedules)")
    plt.ylabel("survival $R_k$")
    plt.ylim(-0.02, 1.02)
    plt.xlim(1, min(kmax, max(hidden_total.values())))
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=7, loc="upper right")
    plt.title("Measured schedule-survival (correct vs. seeded-bug mutants)", fontsize=9)
    plt.tight_layout()
    plt.savefig(os.path.join(FIGDIR, "survival.png"), dpi=160)
    plt.close()

    # ---- Figure 2: failure composition by invariant, per MUTANT TYPE ----
    # Grouping by mutant type (not family) shows each seeded bug is detected via
    # its intended invariant — the oracle-validity result. (Families are
    # structurally uniform at Tier-1, so a per-family view is flat by design.)
    mut_inv = defaultdict(lambda: defaultdict(int))
    inv_tot = defaultdict(int)
    for r in rows:
        if r["ok"] or r["correct_ref"]:
            continue
        t = mutant_type(r["candidate"])
        for v in (r["violations"] or []):
            mut_inv[t][v] += 1
            inv_tot[v] += 1

    mut_order = [t for t in ["m1 unstable-identity", "m2 no-payload-check",
                             "m3 raw-key-only", "m4 vacuous-success",
                             "m5 recovery-loops",
                             "m6 replay-new-reference"] if t in mut_inv]
    import numpy as np
    fig, ax = plt.subplots(figsize=(6.6, 3.6))
    bottom = np.zeros(len(mut_order))
    inv_palette = ["#D55E00", "#E69F00", "#0072B2", "#56B4E9", "#009E73", "#999999"]
    for j, inv in enumerate(INVARIANTS):
        vals = np.array([mut_inv[t].get(inv, 0) for t in mut_order], dtype=float)
        ax.bar([m.split()[0] for m in mut_order], vals, bottom=bottom,
               label=inv.replace("_", " "), color=inv_palette[j % len(inv_palette)])
        bottom += vals
    ax.set_ylabel("invariant violations (across families)")
    ax.set_title("Measured failure composition by seeded-bug type", fontsize=9)
    ax.legend(fontsize=7, ncol=1, loc="center left", bbox_to_anchor=(1.01, 0.5))
    plt.xticks(rotation=0, fontsize=8)
    plt.tight_layout()
    plt.savefig(os.path.join(FIGDIR, "failure_composition.png"), dpi=160, bbox_inches="tight")
    plt.close()
    tex_lines += [
        "%",
        "% ---------------------------------------------------------------------------",
        "% Failure composition. Coordinates are (invariant, violating runs). The",
        "% per-mutant blocks are the stacked series of failure_composition.png: one",
        "% \\addplot per invariant, or one per mutant, depending on the stacking axis.",
        "% Symbolic x coords are the invariant names with underscores stripped.",
        "% ---------------------------------------------------------------------------",
        f"\\def\\invariantnames{{{','.join(tex_name(i) for i in INVARIANTS)}}}",
        f"\\def\\mutantnames{{{','.join(tex_name(t) for t in mut_order)}}}",
    ]
    # Per mutant type: the invariant profile of its failures. Because the mutants
    # are single-fault by construction, each of these should be concentrated in
    # the one invariant that mutant was seeded to break.
    for t in mut_order:
        coords = " ".join(f"({tex_name(inv)},{mut_inv[t].get(inv, 0)})" for inv in INVARIANTS)
        tex_lines.append(f"\\def\\failcomp{tex_name(t)}{{{coords}}}")
    # Transposed view: per invariant, the count contributed by each mutant type.
    for inv in INVARIANTS:
        coords = " ".join(f"({tex_name(t)},{mut_inv[t].get(inv, 0)})" for t in mut_order)
        tex_lines.append(f"\\def\\failinv{tex_name(inv)}{{{coords}}}")
    # Aggregate across all mutants (retained: the paper's existing \faildist).
    coords = " ".join(f"({tex_name(inv)},{inv_tot[inv]})" for inv in INVARIANTS)
    tex_lines.append(f"\\def\\faildist{{{coords}}}")

    # ---- Metrics table ----
    # compile rate, functional (happy) pass rate, unconditional safety, safety|functional
    n_records = len(rows)
    compiled = sum(1 for r in rows if r["compile_status"] == "success")
    # functional correctness proxy = passes the no-fault "happy" schedule
    happy = [r for r in rows if r["schedule_id"].endswith("-happy")]
    happy_pass = sum(1 for r in happy if r["ok"])
    safe_all = sum(1 for r in rows if r["ok"])
    # safety conditional on functional correctness: restrict to candidates that
    # pass their happy schedule, then measure hidden-schedule safety.
    functional_cands = set((r["family"], r["candidate"]) for r in happy if r["ok"])
    cond = [r for r in rows if r["hidden"] and (r["family"], r["candidate"]) in functional_cands]
    cond_pass = sum(1 for r in cond if r["ok"])

    summary = {
        "n_result_records": n_records,
        "n_families": len(set(r["family"] for r in rows)),
        "n_candidates_per_family": len(set(r["candidate"] for r in rows if r["family"] == rows[0]["family"])),
        "compile_rate": round(compiled / n_records, 4),
        "functional_pass_rate_happy": round(happy_pass / max(1, len(happy)), 4),
        "unconditional_safety_rate": round(safe_all / n_records, 4),
        "safety_given_functional_hidden": round(cond_pass / max(1, len(cond)), 4),
        "hidden_survival_R1": {t: round(survival_rk(hidden_pass[t], hidden_total[t], 1), 4) for t in order},
        "hidden_survival_R_at_max_k": {
            t: round(survival_rk(hidden_pass[t], hidden_total[t], min(8, hidden_total[t])), 4) for t in order},
        "invariant_violation_counts": {inv: inv_tot[inv] for inv in INVARIANTS},
        "per_family_safety_rate": {},
    }
    for fam in sorted(set(r["family"] for r in rows)):
        fr = [r for r in rows if r["family"] == fam]
        summary["per_family_safety_rate"][fam] = round(sum(1 for r in fr if r["ok"]) / len(fr), 4)

    with open(os.path.join(ROOT, "results", "metrics_summary.json"), "w") as f:
        json.dump(summary, f, indent=2)

    # per-candidate CSV
    with open(os.path.join(ROOT, "results", "metrics.csv"), "w") as f:
        f.write("candidate_type,all_pass,all_total,hidden_pass,hidden_total,R1,R_maxk\n")
        for t in order:
            n, m = hidden_total[t], hidden_pass[t]
            f.write(f"{t},{all_pass[t]},{all_total[t]},{m},{n},"
                    f"{survival_rk(m,n,1):.4f},{survival_rk(m,n,min(8,n)):.4f}\n")

    with open(os.path.join(FIGDIR, "paper_data.tex"), "w") as f:
        f.write("\n".join(tex_lines) + "\n")

    print("Figures written to", FIGDIR)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
